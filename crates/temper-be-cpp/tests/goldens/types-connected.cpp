#pragma once

#include <temper-core/core.hpp>

namespace work {

// Runs the module's top level, once. Exported functions, constructors,
// static functions, and accessors run it first, so calling it is
// optional.
void global_init_init();

namespace _connected {
struct Counter;
}  // namespace _connected
using Counter = _connected::Counter;
namespace _connected {
struct Doubler;
}  // namespace _connected
using Doubler = _connected::Doubler;

}  // namespace work

// init.cpp
#include <work/init.hpp>

#include "_connected.hpp"

namespace work {

namespace core = temper::core;

void global_init_init() {
  core::init_once([] {
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    std::shared_ptr<Counter> counter = Counter::make();
    counter->add(2);
    counter->add(3);
    core::Console::log(console, "counter.total(): " + std::to_string(counter->total()));
    core::Console::log(console, "new Doubler().twice(5): " + std::to_string(Doubler::make()->twice(5)));
  });
}

}  // namespace work

// _connected.hpp: host code, as it is
// main.cpp
#include "work/init.hpp"

int main() {
  work::global_init_init();
}

