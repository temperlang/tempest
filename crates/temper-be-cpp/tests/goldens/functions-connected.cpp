#include <work/init.hpp>

#include "_connected.hpp"

namespace work {

namespace core = temper::core;

int32_t sumOf3(int32_t a, int32_t b, int32_t c) {
  return core::Int::add(core::Int::add(a, b), c);
}

int32_t sum(int32_t i, int32_t j, core::NullableParam<int32_t> bonus) {
  global_init_init();
  int32_t bonus2 = bonus == nullptr ? 0 : bonus.value;
  return _connected::sum(i, j, bonus2);
}

int32_t sum(int32_t i, int32_t j) {
  return sum(i, j, nullptr);
}

int32_t length(core::NullableParam<core::Str> string) {
  global_init_init();
  return _connected::length(string);
}

int32_t length() {
  return length(nullptr);
}

int32_t twice(int32_t i) {
  global_init_init();
  return _connected::twice(i);
}

std::shared_ptr<Hidden> Hidden::make(int32_t i) {
  std::shared_ptr<Hidden> self = std::make_shared<Hidden>();
  self->i = i;
  return self;
}

int32_t Hidden::get_i() const {
  return this->i;
}

static int32_t prod(std::shared_ptr<Hidden> const & hidden, int32_t j) {
  return _connected::prod(hidden, j);
}

std::shared_ptr<Hider> Hider::make(int32_t i) {
  global_init_init();
  std::shared_ptr<Hider> self = std::make_shared<Hider>();
  self->i = i;
  self->hidden = Hidden::make(self->i);
  return self;
}

int32_t Hider::plus(int32_t j) const {
  std::shared_ptr<Hider const> self = shared_from_this();
  return work::sum(self->hidden->i, j);
}

int32_t Hider::times(int32_t j) const {
  std::shared_ptr<Hider const> self = shared_from_this();
  return work::prod(self->hidden, j);
}

void global_init_init() {
  core::init_once([] {
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    core::Console::log(console, "sum(1, 2): " + std::to_string(work::sum(1, 2)));
    core::Console::log(console, "length \"\" vs null vs (): " + std::to_string(work::length(core::Str())) + " vs " + std::to_string(work::length(nullptr)) + " vs " + std::to_string(work::length()));
    core::Console::log(console, "twice(5): " + std::to_string(twice(5)));
    bool isConnected = work::sum(1, 2) == 3;
    if (isConnected) {
      core::Console::log(console, "prod(new Hidden(1), 2): " + std::to_string(work::prod(Hidden::make(1), 2)));
    }
    std::shared_ptr<Hider> hider = Hider::make(3);
    core::Console::log(console, "new Hider(3).plus(4): " + std::to_string(hider->plus(4)));
    if (isConnected) {
      core::Console::log(console, "new Hider(3).times(4): " + std::to_string(hider->times(4)));
    }
  });
}

}  // namespace work

