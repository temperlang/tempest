struct Hidden;
struct Hider;

struct Hidden : public std::enable_shared_from_this<Hidden> {
  int32_t i;
  static std::shared_ptr<Hidden> make(int32_t i);
  int32_t get_i() const;
};

struct Hider : public std::enable_shared_from_this<Hider> {
  int32_t i;
  std::shared_ptr<Hidden> hidden;
  static std::shared_ptr<Hider> make(int32_t i);
  int32_t plus(int32_t j) const;
  int32_t times(int32_t j) const;
};

