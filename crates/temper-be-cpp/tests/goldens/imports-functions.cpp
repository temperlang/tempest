#pragma once

#include <temper-core/core.hpp>
#include <functions/exporter.hpp>

namespace functions {

// Runs the module's top level, once. Exported functions, constructors,
// static functions, and accessors run it first, so calling it is
// optional.
void global_init_init();

double norm(double x, double y);
double something(std::shared_ptr<std::vector<double>> const & vals);

}  // namespace functions

// init.cpp
#include <functions/init.hpp>

namespace functions {

namespace core = temper::core;

double norm(double x, double y) {
  global_init_init();
  return core::Float64::sqrt(normSquared(x, y));
}

double something(std::shared_ptr<std::vector<double>> const & vals) {
  global_init_init();
  return core::List::reduceFrom(vals, 0.0, normSquared);
}

void global_init_init() {
  core::init_once([] {
    global_init_exporter();
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    double a = 3.0;
    double b = a + 1.0;
    std::string values = core::List::join(core::List::make<double>(a, b, norm(a, b)), ", ", [](double it) -> std::string { return core::Float64::toString(it); });
    core::Console::log(console, values + " triangle");
    core::Console::log(console, core::Float64::toString(functions::something(core::List::make<double>(a, b))));
  });
}

}  // namespace functions

// main.cpp
#include "functions/exporter.hpp"
#include "functions/init.hpp"

int main() {
  functions::global_init_exporter();
  functions::global_init_init();
}

