// init.hpp
#pragma once

#include <temper-core/core.hpp>

namespace work {

// Runs the module's top level, once. Exported functions, constructors,
// static functions, and accessors run it first, so calling it is
// optional.
void global_init_init();

struct Counter;
struct Doubler;

struct Counter : public std::enable_shared_from_this<Counter> {
  int32_t count;
  static std::shared_ptr<Counter> make();
  void add(int32_t i);
  int32_t total() const;
};

struct Doubler : public std::enable_shared_from_this<Doubler> {
  static std::shared_ptr<Doubler> make();
  int32_t twice(int32_t i) const;
};

}  // namespace work

// init.cpp
#include <work/init.hpp>

namespace work {

namespace core = temper::core;

std::shared_ptr<Counter> Counter::make() {
  global_init_init();
  std::shared_ptr<Counter> self = std::make_shared<Counter>();
  self->count = 0;
  return self;
}

void Counter::add(int32_t i) {
  this->count = core::Int::add(this->count, i);
}

int32_t Counter::total() const {
  return core::Int::add(this->count, 1000);
}

std::shared_ptr<Doubler> Doubler::make() {
  global_init_init();
  std::shared_ptr<Doubler> self = std::make_shared<Doubler>();
  return self;
}

int32_t Doubler::twice(int32_t i) const {
  return core::Int::add(core::Int::mul(i, 2), 1000);
}

void global_init_init() {
  core::init_once([] {
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    std::shared_ptr<Counter> counter = Counter::make();
    counter->add(2);
    counter->add(3);
    core::Console::log(console, "counter.total(): " + std::to_string(counter->total()));
    core::Console::log(console, "new Doubler().twice(5): " + std::to_string(Doubler::make()->twice(5)));
  });
}

}  // namespace work

// _connected.hpp: host code, as it is
// main.cpp
#include "work/init.hpp"

int main() {
  work::global_init_init();
}

