// exporter.cpp
#include <values/exporter.hpp>

#include <mutex>

namespace values {

namespace core = temper::core;

int32_t magicNumber;

static std::shared_ptr<std::vector<int32_t>> foo() {
  return core::List::make<int32_t>(core::Int::add(21, 21), 42);
}

void global_init_exporter() {
  static std::once_flag once;
  std::call_once(once, [] {
    int32_t a = core::List::get<int32_t>(foo(), 0);
    magicNumber = a;
  });
}

}  // namespace values

// init.hpp
#pragma once

#include <temper-core/core.hpp>
#include <values/exporter.hpp>

namespace values {

int32_t timesMagic(int32_t n);

// Runs the module's top level, once; call it before anything else.
void global_init_init();

}  // namespace values

// init.cpp
#include <values/init.hpp>

#include <mutex>

namespace values {

namespace core = temper::core;

int32_t timesMagic(int32_t n) {
  return core::Int::mul(n, magicNumber);
}

void global_init_init() {
  static std::once_flag once;
  std::call_once(once, [] {
    global_init_exporter();
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    int32_t a = 1;
    int32_t c = timesMagic(a);
    core::Console::log(console, "number = " + std::to_string(c));
  });
}

}  // namespace values

// main.cpp
#include "values/exporter.hpp"
#include "values/init.hpp"

int main() {
  values::global_init_exporter();
  values::global_init_init();
}

