// init.cpp
#include <testing/init.hpp>

#include <mutex>

namespace testing {

namespace core = temper::core;

namespace temper_globals {

static core::GlobalSlot<int32_t> runs;
static core::GlobalSlot<int32_t> base;

}  // namespace temper_globals

static std::mutex moduleMutex;

// Reads a variable that functions write, under the module's lock.
template <class T>
static T load(T const &variable) {
  std::lock_guard<std::mutex> lock(moduleMutex);
  return variable;
}

int32_t twice(int32_t n) {
  global_init_init();
  return core::Int::mul(n, 2);
}

void global_init_init() {
  core::init_once([] {
    temper_globals::runs.construct();
    temper_globals::base.construct();
    std::shared_ptr<core::Console::Type> console = core::Console::get_console();
    temper_globals::runs.value = 0;
    temper_globals::base.value = 10;
    core::Console::log(console, "init " + std::to_string(twice(1)));
  });
}

}  // namespace testing

#ifdef TEMPER_TESTS

namespace testing {

void twiceWorks(std::shared_ptr<temper_std::Test> const &) {
  int32_t x = twice(2);
  std::lock_guard<std::mutex> lock(moduleMutex);
  temper_globals::runs.value = core::Int::add(core::Int::add(temper_globals::runs.value, x), temper_globals::base.value);
}

void namesPunctuationQuotesAndNCode(std::shared_ptr<temper_std::Test> const &) {
  twice(load(temper_globals::runs.value));
}

}  // namespace testing

#endif  // TEMPER_TESTS

// main.cpp
#include "testing/init.hpp"

int main() {
  testing::global_init_init();
}

// test.cpp
#include "testing/init.hpp"
#include "temper-core/test_main.hpp"

int main() {
  testing::global_init_init();
  temper_std::global_init_testing();
  return temper::core::run_tests({
      {"twice works", [] {
        auto test = temper_std::Test::make();
        testing::twiceWorks(test);
        auto messages = test->messagesCombined();
        return temper::core::TestOutcome{
            test->get_passing(),
            temper::core::is_null(messages) ? std::string() : static_cast<std::string>(messages)};
      }},
      {"names: punctuation, 'quotes', and ünïcode", [] {
        auto test = temper_std::Test::make();
        testing::namesPunctuationQuotesAndNCode(test);
        auto messages = test->messagesCombined();
        return temper::core::TestOutcome{
            test->get_passing(),
            temper::core::is_null(messages) ? std::string() : static_cast<std::string>(messages)};
      }},
  });
}

