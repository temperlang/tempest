fn case(kind: DeclKind, _exported: bool) -> Case {
    match kind {
        DeclKind::Class | DeclKind::Interface => Case::Keep,
        _ => Case::Snake,
    }
}

fn identifier(c: char, first: bool) -> bool {
    c == '_' || c.is_alphabetic() || (!first && c.is_alphanumeric())
}

/// The first variant's rules.
pub const RULES: NamingRules = NamingRules {
    reserved: &[KEYWORDS, BUILTINS, IMPORTED],
    case,
    private_prefix: "_",
    escape_suffix: "_",
    raw_keywords: &[],
    raw_prefix: "",
    identifier,
};

/// A library's or module's name as a Python package or module: dashes
/// become underscores, and a reserved word gets a trailing `_`
/// (`control_flow/async_`), as Kotlin's.
pub fn package_name(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| if c == '-' || c == '.' { '_' } else { c })
        .collect();
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}
