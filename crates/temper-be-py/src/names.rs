/// A library's or module's name as a Python package or module: dashes
/// become underscores, and a reserved word gets a trailing `_`
/// (`control_flow/async_`), as Kotlin's.
pub fn package_name(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| if c == '-' || c == '.' { '_' } else { c })
        .collect();
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

/// A library's name as its top-level Python package: as
/// [`package_name`], and with a trailing `_` if a standard module has
/// its name (`types_`), which Kotlin leaves as it is, where the library
/// can't be imported.
pub fn library_package(name: &str) -> String {
    let mut out = package_name(name);
    if STDLIB.contains(&out.as_str()) {
        out.push('_');
    }
    out
}
