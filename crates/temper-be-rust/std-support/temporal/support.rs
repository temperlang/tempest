use crate::temporal::Date;

/// Today's date in UTC, from the system clock, with only Rust's std:
/// days since the Unix epoch to a proleptic Gregorian date (Howard
/// Hinnant's `civil_from_days`).
#[cfg(feature = "temporal")]
pub fn today() -> temper_core::Result<Date> {
    let secs = match std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH) {
        Ok(d) => d.as_secs() as i64,
        Err(e) => -(e.duration().as_secs() as i64) - 1,
    };
    let z = secs.div_euclid(86_400) + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    Date::new(year as i32, month as i32, day as i32)
}
