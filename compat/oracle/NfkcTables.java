import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.List;
import java.util.Random;
import java.util.TreeMap;
import jdk.internal.icu.lang.UCharacter;
import jdk.internal.icu.util.VersionInfo;

/**
 * Writes the tables temper-syntax's `nfkc` module needs to tell whether
 * text is in Unicode NFKC, taking the JDK's java.text.Normalizer (which
 * Kotlin Temper uses) as the source of truth, and test cases with the
 * JDK's answers. Run by compat/gen_nfkc.py.
 *
 *     java --add-exports java.base/jdk.internal.icu.lang=ALL-UNNAMED \
 *          --add-exports java.base/jdk.internal.icu.util=ALL-UNNAMED \
 *          NfkcTables TABLES.rs CASES.txt NOTICE_TEXT_FILE
 *
 * The JDK has no public API for canonical combining classes or its Unicode
 * version, so this reads them from its internal copy of ICU.
 */
public class NfkcTables {
    static final int MAX = 0x10FFFF;

    static String str(int... cps) {
        return new String(cps, 0, cps.length);
    }

    static boolean isSurrogate(int c) {
        return c >= 0xD800 && c <= 0xDFFF;
    }

    static boolean isHangulSyllable(int c) {
        return c >= 0xAC00 && c <= 0xD7A3;
    }

    static String nfc(String s) {
        return Normalizer.normalize(s, Normalizer.Form.NFC);
    }

    static boolean isNfkc(String s) {
        return Normalizer.normalize(s, Normalizer.Form.NFKC).equals(s);
    }

    public static void main(String[] args) throws Exception {
        String version = unicodeVersion();

        // Code points that NFKC changes on their own: these never appear in
        // NFKC text. Surrogates count as unchanged, to merge ranges; Rust
        // strings can't hold them.
        List<Integer> notNfkc = new ArrayList<>();
        boolean in = false;
        for (int c = 0; c <= MAX + 1; c++) {
            boolean no = c <= MAX && !isSurrogate(c) && !isNfkc(str(c));
            if (no != in) {
                notNfkc.add(c);
                in = no;
            }
        }

        // Canonical combining classes, as runs: each start and its class.
        List<int[]> ccc = new ArrayList<>();
        int previous = -1;
        for (int c = 0; c <= MAX; c++) {
            int cc = UCharacter.getCombiningClass(c);
            if (cc != previous) {
                ccc.add(new int[] {c, cc});
                previous = cc;
            }
        }

        // Primary composites that NFKC keeps, with the pair each composes
        // from. Composing its decomposition, which is in canonical order,
        // must take in every mark in turn, so the last step is the rest's
        // composite with the last mark: that's the pair NFC looks up. Hangul
        // syllables compose by arithmetic instead.
        TreeMap<Integer, int[]> pairs = new TreeMap<>();
        for (int c = 0; c <= MAX; c++) {
            if (isSurrogate(c) || isHangulSyllable(c) || !isNfkc(str(c))) {
                continue;
            }
            int[] d = Normalizer.normalize(str(c), Normalizer.Form.NFD).codePoints().toArray();
            if (d.length == 1) {
                continue;
            }
            int last = d[d.length - 1];
            int[] first = nfc(str(java.util.Arrays.copyOf(d, d.length - 1))).codePoints().toArray();
            if (first.length != 1 || !nfc(str(first[0], last)).equals(str(c))) {
                System.err.println("no pair for " + Integer.toHexString(c));
                System.exit(1);
            }
            pairs.put(c, new int[] {first[0], last});
        }

        String notice = Files.readString(Path.of(args[2]), StandardCharsets.UTF_8);
        try (PrintStream out = new PrintStream(Files.newOutputStream(Path.of(args[0])), false, "UTF-8")) {
            out.println("//! Generated by compat/gen_nfkc.py from the JDK's java.text.Normalizer");
            out.println("//! (Java " + System.getProperty("java.version") + ", Unicode " + version
                    + "); don't edit. See `nfkc` for how they're used.");
            out.println("//!");
            out.println("//! Derived from the Unicode Character Database, under this notice:");
            out.println("//!");
            for (String line : notice.strip().split("\n")) {
                out.println(line.isEmpty() ? "//!" : "//! " + line);
            }
            out.println();
            out.println("/// The Unicode version the tables come from.");
            out.println("pub const UNICODE_VERSION: &str = \"" + version + "\";");
            out.println();
            out.println("/// Code points NFKC changes on their own, as sorted `[start, end)` pairs.");
            out.println("pub static NOT_NFKC: &[u32] = &[");
            printInts(out, notNfkc.stream().mapToInt(Integer::intValue).toArray());
            out.println("];");
            out.println();
            out.println("/// Canonical combining classes, as runs: each run's first code point.");
            out.println("pub static CCC_STARTS: &[u32] = &[");
            printInts(out, ccc.stream().mapToInt(r -> r[0]).toArray());
            out.println("];");
            out.println();
            out.println("/// Each run's class.");
            out.println("pub static CCC_VALUES: &[u8] = &[");
            printInts(out, ccc.stream().mapToInt(r -> r[1]).toArray());
            out.println("];");
            out.println();
            out.println("/// Primary composites NFKC keeps, sorted, with the pairs they compose from:");
            out.println("/// `[composite, first, second]`. Hangul syllables aren't listed.");
            out.println("pub static COMPOSITES: &[[u32; 3]] = &[");
            StringBuilder line = new StringBuilder("   ");
            for (var e : pairs.entrySet()) {
                String item = " [" + e.getKey() + ", " + e.getValue()[0] + ", " + e.getValue()[1] + "],";
                if (line.length() + item.length() > 100) {
                    out.println(line);
                    line = new StringBuilder("   ");
                }
                line.append(item);
            }
            out.println(line);
            out.println("];");
            out.println();
            out.println("/// The pairs' second code points, sorted: those that may compose with what");
            out.println("/// precedes them, apart from Hangul jamo.");
            out.println("pub static SECONDS: &[u32] = &[");
            printInts(out, pairs.values().stream().mapToInt(p -> p[1]).distinct().sorted().toArray());
            out.println("];");
        }

        // Test cases: each composite and its decomposition, a composite
        // followed by each mark that may compose or reorder with it, and
        // random mixes of letters, composites, marks and Hangul jamo.
        List<Integer> marks = new ArrayList<>();
        for (int[] p : pairs.values()) {
            if (!marks.contains(p[1])) {
                marks.add(p[1]);
            }
        }
        List<Integer> composites = new ArrayList<>(pairs.keySet());
        List<String> cases = new ArrayList<>();
        for (int c : composites) {
            cases.add(str(c));
            cases.add(Normalizer.normalize(str(c), Normalizer.Form.NFD));
        }
        for (int c : composites) {
            if (c < 0x2000) {
                for (int m : marks) {
                    if ((c + m) % 41 == 0) {
                        cases.add(str(c, m));
                    }
                }
            }
        }
        Random random = new Random(15);
        int[] pool = {
            'a', 'e', 'o', 'u', 'A', 0x3B1, 0x1100, 0x1161, 0x11A8, 0xAC00, 0xAC01, 0x0B47, 0x0B3E, 0x0301,
            0x0308, 0x0323, 0x0327, 0x0334, 0x0345, 0x05B0, 0x0F71, 0x0F72, 0x1E9B, 0x00AA, 0xFB01,
        };
        for (int i = 0; i < 1000; i++) {
            int n = 1 + random.nextInt(4);
            int[] cps = new int[n];
            for (int j = 0; j < n; j++) {
                int pick = random.nextInt(3);
                cps[j] = pick == 0 ? pool[random.nextInt(pool.length)]
                        : pick == 1 ? composites.get(random.nextInt(composites.size()))
                        : marks.get(random.nextInt(marks.size()));
            }
            cases.add(str(cps));
        }
        try (PrintStream out = new PrintStream(Files.newOutputStream(Path.of(args[1])), false, "UTF-8")) {
            out.println("# Generated by compat/gen_nfkc.py: code points, then whether the JDK");
            out.println("# (Unicode " + version + ") finds them in NFKC.");
            for (String s : cases) {
                StringBuilder b = new StringBuilder();
                s.codePoints().forEach(cp -> b.append(Integer.toHexString(cp)).append(' '));
                b.setLength(b.length() - 1);
                out.println(b + "\t" + (isNfkc(s) ? "yes" : "no"));
            }
        }
    }

    /** The JDK's Unicode version, found by comparison: VersionInfo has no getters. */
    static String unicodeVersion() {
        VersionInfo v = UCharacter.getUnicodeVersion();
        for (int major = 6; major < 40; major++) {
            for (int minor = 0; minor < 10; minor++) {
                for (int milli = 0; milli < 10; milli++) {
                    if (v.compareTo(VersionInfo.getInstance(major, minor, milli, 0)) == 0) {
                        return major + "." + minor + "." + milli;
                    }
                }
            }
        }
        throw new IllegalStateException("unknown Unicode version");
    }

    static void printInts(PrintStream out, int[] values) {
        StringBuilder line = new StringBuilder("   ");
        for (int value : values) {
            String item = " " + value + ",";
            if (line.length() + item.length() > 100) {
                out.println(line);
                line = new StringBuilder("   ");
            }
            line.append(item);
        }
        out.println(line);
    }
}
